#!/usr/bin/env bash
# _gate_git_ctx.sh — sourced helper for cron_gate.sh.
#
# WHY: the project-note LLM workers (Advancer / Improver) do heavy on-disk drift
# checks (Step 4a/4b: "did this ship out-of-band in a live session?"). Today they
# probe blind. This helper captures a cheap, bounded git-diff digest of what
# ACTUALLY changed in the repo recently and drops it in a per-lane context file
# that the worker reads at its Step 0.5. The worker then knows where to look
# first instead of guessing.
#
# COST CONTRACT (the whole point):
#   - This runs git only (HARDWARE cost, zero LLM). Owner accepts hardware cost.
#   - It is called ONLY from cron_gate.sh trigger() — i.e. ONLY after a gate has
#     already returned exit 0 (genuine work). Empty ticks hit exit 1, trigger()
#     is never called, git never runs, no file is written → zero LLM, near-zero
#     hardware on idle ticks.
#
# FAIL-OPEN CONTRACT (keeps this "support only", never gate-influencing):
#   - Every git call is guarded + timeout-bounded. ANY failure/flake → we remove
#     any stale context file and return 0. The worker then simply finds no ctx
#     file and proceeds on its existing signals exactly as before. git can never
#     block a fire, manufacture an empty one, or change WHAT fires.
#   - The context is ADVISORY drift-hint input to an LLM that already independently
#     verifies every artifact against done_when. Wrong/empty ctx costs nothing.

# Directory where per-lane context files live. Workers read <lane>.md here.
GATE_GIT_CTX_DIR="${GATE_GIT_CTX_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/.gate_git_ctx}"

# write_git_ctx <lane> <repo_root>
# Best-effort. Writes $GATE_GIT_CTX_DIR/<lane>.md or removes it on any failure.
write_git_ctx() {
  local lane="$1" repo="${2:-/root/.openclaw}"
  local outdir="$GATE_GIT_CTX_DIR"
  local out="$outdir/${lane}.md"

  # fail-open: if anything below can't run cleanly, ensure no stale file lingers.
  _gitctx_bail() { rm -f "$out" 2>/dev/null || true; return 0; }

  command -v git >/dev/null 2>&1 || { _gitctx_bail; return 0; }
  [ -d "$repo/.git" ] || { _gitctx_bail; return 0; }
  mkdir -p "$outdir" 2>/dev/null || { _gitctx_bail; return 0; }

  # Bounded, quote-safe git reads. 10s ceiling each so a wedged git never stalls
  # the $0 dispatcher. --no-optional-locks avoids fighting a concurrent git op.
  local G=(timeout 10 git -C "$repo" --no-optional-locks -c core.quotepath=false)

  local head_line worktree last_commit
  head_line="$("${G[@]}" rev-parse --short HEAD 2>/dev/null)" || { _gitctx_bail; return 0; }
  # working-tree changes (staged + unstaged), name+stat, bounded to memory + scripts
  # + common artifact dirs so the digest stays small and relevant.
  worktree="$("${G[@]}" diff --stat --stat-width=100 HEAD 2>/dev/null)" || worktree=""
  # last commit summary + files it touched (catches work committed out-of-band).
  last_commit="$("${G[@]}" show --stat --oneline -s HEAD 2>/dev/null)" || last_commit=""
  local last_files
  last_files="$("${G[@]}" show --stat --oneline HEAD 2>/dev/null | tail -n +2)" || last_files=""
  # untracked files (new artifacts a project may have produced but not committed).
  local untracked
  untracked="$("${G[@]}" ls-files --others --exclude-standard 2>/dev/null | head -40)" || untracked=""

  # If git gave us literally nothing useful, don't leave an empty/misleading file.
  if [ -z "$worktree" ] && [ -z "$last_files" ] && [ -z "$untracked" ]; then
    _gitctx_bail
    return 0
  fi

  # Atomic write via temp + mv so a worker never reads a half-written file.
  local tmp="${out}.tmp.$$"
  {
    echo "# git drift context — lane: $lane"
    echo "# ADVISORY ONLY. Generated by _gate_git_ctx.sh on gate fire. Repo: $repo @ $head_line"
    echo "# Use as a HINT for Step 4a/4b drift checks (what changed on disk). Still verify"
    echo "# every artifact against done_when independently. If this looks stale/wrong, ignore it."
    echo "# Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo
    if [ -n "$worktree" ]; then
      echo "## Uncommitted working-tree changes (vs HEAD)"
      echo '```'
      printf '%s\n' "$worktree"
      echo '```'
      echo
    fi
    if [ -n "$last_commit" ] || [ -n "$last_files" ]; then
      echo "## Most recent commit (may be out-of-band work)"
      echo '```'
      [ -n "$last_commit" ] && printf '%s\n' "$last_commit"
      [ -n "$last_files" ] && printf '%s\n' "$last_files"
      echo '```'
      echo
    fi
    if [ -n "$untracked" ]; then
      echo "## Untracked files (new artifacts, not yet committed)"
      echo '```'
      printf '%s\n' "$untracked"
      echo '```'
      echo
    fi
  } > "$tmp" 2>/dev/null || { rm -f "$tmp" 2>/dev/null; _gitctx_bail; return 0; }

  mv -f "$tmp" "$out" 2>/dev/null || { rm -f "$tmp" 2>/dev/null; _gitctx_bail; return 0; }
  return 0
}
